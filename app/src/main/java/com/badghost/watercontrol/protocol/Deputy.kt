/**
 * Kotlin port of the exported `makeKey` function of `deputy.wat`.
 *
 * `makeKey($0, $1, $2, $3)` writes the resulting 32-bit key to bytes `2096..2099`
 * of the WASM linear memory, which the original TypeScript reads back as a
 * little-endian `Uint32` and then converts to big-endian bytes. This port
 * returns those four bytes directly in the same order.
 */
object Deputy {

    /**
     * Derives the raw 4-byte unlock key.
     *
     * @param a first key input byte (the nonce high byte)
     * @param b second key input byte (the nonce low byte)
     * @param c third key input byte (MAC low byte)
     * @param d fourth key input byte (MAC high byte)
     * @return the 4 key bytes, in the same order the original returns them
     */
    fun makeKey(a: Int, b: Int, c: Int, d: Int): ByteArray {
        val inA: Int = b and 0xFF
        val inB: Int = c and 0xFF
        val inC: Int = d and 0xFF

        var vA = a
        var vD = d

        // (if (and (eq b 255) (eq (and a 1) 1)) (then (local.set a (add a 2))))
        if (inA == 255 && (vA and 1) == 1) vA += 2
        // (if (eq a 257) (then (local.set a 0)))
        if (vA == 257) vA = 0

        // --- iA: derived from `d`, then a table lookup on `b`, then from `a` ---
        var iA = vD and 7
        // (local.set m (and d (xor -1 7))) -- all bits of d except the low three
        val maskD = vD and 7.inv()
        if (maskD and 8 != 0) iA = iA xor 4   // bit 3 of d
        if (maskD and 16 != 0) iA = iA xor 4  // bit 4 of d
        if (maskD and 32 != 0) iA = iA xor 4  // bit 5 of d
        if (maskD and 64 != 0) iA = iA xor 4  // bit 6 of d
        if (maskD and 128 != 0) iA = iA xor 4 // bit 7 of d
        iA = iA xor DeputyTable.u8(inA)       // i32.load8_u (0 + b)
        if (vA and 1 != 0) iA = iA xor 1      // bit 0 of a
        if (vA and 2 != 0) iA = iA xor 1      // bit 1 of a
        if (vA and 4 != 0) iA = iA xor 2      // bit 2 of a
        if (vA and 8 != 0) iA = iA xor 7      // bit 3 of a
        if (vA and 16 != 0) iA = iA xor 1     // bit 4 of a
        if (vA and 32 != 0) iA = iA xor 1     // bit 5 of a
        if (vA and 64 != 0) iA = iA xor 1     // bit 6 of a
        if (vA and 128 != 0) iA = iA xor 1    // bit 7 of a

        // --- iC: same shape as iA but derived from `c` and a nibble of `b` ---
        var iC = inB and 7
        val maskC = inB and 7.inv()
        if (maskC and 8 != 0) iC = iC xor 4
        if (maskC and 16 != 0) iC = iC xor 4
        if (maskC and 32 != 0) iC = iC xor 4
        if (maskC and 64 != 0) iC = iC xor 4
        if (maskC and 128 != 0) iC = iC xor 4
        iC = iC xor DeputyTable.u8(768 + (inA and 15)) // i32.load8_u (768 + (b and 15))

        // --- state updates -------------------------------------------------
        // (local.set d (xor (load8_u (256 + b)) d)) then (xor (load8_u (512 + a)) d)
        // NOTE: after the first xor, `d` is a full i32; the WASM `i32.load8_u` then
        // takes (512 + d) modulo 2^32. In practice `d` only ever grows to a small
        // value here, so a plain Int index reproduces the original behaviour.
        vD = vD xor DeputyTable.u8(256 + inA)
        vD = vD xor DeputyTable.u8(512 + vA)
        val iB = DeputyTable.u8(1296 + vD)

        // (local.set c (xor (load8_u (784 + b)) c)) then (xor (load8_u (1040 + a)) c)
        var vC = inB xor DeputyTable.u8(784 + inA)
        vC = vC xor DeputyTable.u8(1040 + vA)
        val iD = DeputyTable.u8(1552 + vC)

        // --- store8 to 2099, 2098, 2097, 2096 (i.e. a little-endian u32 at 2096) ---
        val k3 = DeputyTable.u8(1938 + iA)
        val k2 = DeputyTable.u8(1808 + iB)
        val k1 = DeputyTable.u8(2082 + iC)
        val k0 = DeputyTable.u8(1952 + iD)

        // The original reads `new Uint32Array(memory.buffer)[524]` (little-endian) and
        // emits [(key >> 24), (key >> 16), (key >> 8), key] -- i.e. big-endian order.
        return byteArrayOf(k3.toByte(), k2.toByte(), k1.toByte(), k0.toByte())
    }
